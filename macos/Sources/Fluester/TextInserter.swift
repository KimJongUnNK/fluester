import AppKit
import ApplicationServices
import Carbon.HIToolbox
import FluesterCore

/// Text in die aktive App bringen – per Einfügen (Zwischenablage wird danach wiederhergestellt) oder per Tippen.
enum TextInserter {

    /// Fügt ein. Liefert false, wenn kein Textfeld erkennbar war (Text liegt dann in der Zwischenablage).
    @discardableResult
    static func insert(_ text: String, method: InsertMethod, smartSpacing: Bool) -> Bool {
        var t = text
        if smartSpacing, let prev = precedingCharacter(), needsSpace(after: prev, before: t) { t = " " + t }
        let hasField = focusedElement() != nil
        switch method {
        case .paste: paste(t, restore: hasField)
        case .type: type(t)
        }
        return hasField
    }

    static func needsSpace(after prev: Character, before text: String) -> Bool {
        guard let first = text.first, first.isLetter || first.isNumber || "„\"(".contains(first) else { return false }
        if prev.isWhitespace || prev.isNewline { return false }
        if "([{„\"'/-–@#".contains(prev) { return false }
        return true
    }

    // MARK: Einfügen

    static func paste(_ text: String, restore: Bool) {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        pb.clearContents()
        pb.setString(text, forType: .string)
        // Zwischenablage-Manager sollen den Zwischenstand ignorieren
        pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let change = pb.changeCount
        postKey(CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
        guard restore else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
            // Hat der Nutzer inzwischen selbst etwas kopiert? Dann nicht überschreiben.
            guard pb.changeCount == change else { return }
            restoreSnapshot(saved, to: pb)
        }
    }

    typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    static func snapshot(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let v = item.data(forType: type) { d[type] = v }
            }
            return d
        }
    }

    static func restoreSnapshot(_ saved: Snapshot, to pb: NSPasteboard) {
        pb.clearContents()
        let items: [NSPasteboardItem] = saved.map { dict in
            let it = NSPasteboardItem()
            for (k, v) in dict { it.setData(v, forType: k) }
            return it
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    // MARK: Tippen

    static func type(_ text: String) {
        let src = CGEventSource(stateID: .hidSystemState)
        var buffer: [UniChar] = []
        func flush() {
            guard !buffer.isEmpty else { return }
            buffer.withUnsafeBufferPointer { p in
                let down = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: true)
                down?.keyboardSetUnicodeString(stringLength: p.count, unicodeString: p.baseAddress)
                down?.post(tap: .cghidEventTap)
                let up = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: false)
                up?.keyboardSetUnicodeString(stringLength: p.count, unicodeString: p.baseAddress)
                up?.post(tap: .cghidEventTap)
            }
            buffer.removeAll()
            usleep(4000)
        }
        for ch in text {
            if ch == "\n" {
                flush()
                // ⇧↩ statt ↩, damit Chats nicht abschicken
                postKey(CGKeyCode(kVK_Return), flags: .maskShift)
                usleep(4000)
                continue
            }
            buffer.append(contentsOf: Array(String(ch).utf16))
            if buffer.count >= 18 { flush() }
        }
        flush()
    }

    static func postKey(_ key: CGKeyCode, flags: CGEventFlags) {
        let src = CGEventSource(stateID: .hidSystemState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true)
        down?.flags = flags
        let up = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false)
        up?.flags = flags
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: Bedienungshilfen: Fokus, Auswahl, Zeichen davor

    static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success, let v = value else { return nil }
        // swiftlint:disable:next force_cast
        return (v as! AXUIElement)
    }

    /// Markierter Text über Bedienungshilfen (klappt in nativen Apps).
    static func selectedTextAX() -> String? {
        guard let el = focusedElement() else { return nil }
        var value: CFTypeRef?
        if AXUIElementCopyAttributeValue(el, kAXSelectedTextAttribute as CFString, &value) == .success,
           let s = value as? String, !s.isEmpty {
            return s
        }
        return nil
    }

    /// Markierung per ⌘C holen (Electron-Apps, Browser). Zwischenablage wird wiederhergestellt.
    static func copySelection() async -> String? {
        let saved: Snapshot = await MainActor.run { snapshot(NSPasteboard.general) }
        let before = await MainActor.run { NSPasteboard.general.changeCount }
        postKey(CGKeyCode(kVK_ANSI_C), flags: .maskCommand)
        try? await Task.sleep(nanoseconds: 220_000_000)
        return await MainActor.run {
            let pb = NSPasteboard.general
            let text = pb.changeCount != before ? pb.string(forType: .string) : nil
            if pb.changeCount != before { restoreSnapshot(saved, to: pb) }
            return (text?.isEmpty ?? true) ? nil : text
        }
    }

    /// Zeichen direkt vor dem Cursor, für automatisches Leerzeichen.
    static func precedingCharacter() -> Character? {
        guard let el = focusedElement() else { return nil }
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rv = rangeValue, CFGetTypeID(rv) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        // swiftlint:disable:next force_cast
        guard AXValueGetValue(rv as! AXValue, .cfRange, &range), range.location > 0 else { return nil }
        var prevRange = CFRange(location: range.location - 1, length: 1)
        if let param = AXValueCreate(.cfRange, &prevRange) {
            var str: CFTypeRef?
            if AXUIElementCopyParameterizedAttributeValue(el, kAXStringForRangeParameterizedAttribute as CFString, param, &str) == .success,
               let s = str as? String, let c = s.last {
                return c
            }
        }
        var full: CFTypeRef?
        if AXUIElementCopyAttributeValue(el, kAXValueAttribute as CFString, &full) == .success, let s = full as? String {
            let ns = s as NSString
            if range.location - 1 < ns.length {
                let r = ns.rangeOfComposedCharacterSequence(at: range.location - 1)
                return Character(ns.substring(with: r))
            }
        }
        return nil
    }
}
